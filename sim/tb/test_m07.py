"""M07 RTL vs stored M00 traces and NIST GCM authentication vectors."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from iverilog_runner import compile_iverilog

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pc/src/host"))
from crypto_ref import gf128_mul, ghash_trace


def tool(name):
    found = shutil.which(name)
    if found:
        return found
    windows = Path(f"C:/iverilog/bin/{name}.exe")
    if os.name == "nt" and windows.is_file():
        return str(windows)
    raise RuntimeError(f"Install {name} or add it to PATH")


class M07(unittest.TestCase):
    def test_ghash_rtl(self):
        m00 = json.loads((ROOT / "sim/vectors/aes_gcm.json").read_text())["vectors"]
        nist = json.loads((ROOT / "data/kat/nist_gcm.json").read_text())["vectors"]
        self.assertEqual((len(m00), len(nist)), (80, 20))
        for field in ("aad", "ciphertext"):
            lengths = [len(bytes.fromhex(v[field])) for v in m00 + nist]
            self.assertIn(0, lengths)
            self.assertTrue(any(length % 16 for length in lengths))
        lines = []
        pairs = [(0, 0), (1, 1 << 127), ((1 << 128) - 1, (1 << 128) - 1)]
        for i in range(29):
            raw = hashlib.shake_256(f"M07 GF {i}".encode()).digest(32)
            pairs.append((int.from_bytes(raw[:16], "big"), int.from_bytes(raw[16:], "big")))
        lines.append(str(len(pairs)))
        lines.extend(f"{x:032x} {y:032x} {gf128_mul(x, y):032x}" for x, y in pairs)
        lines.append(str(len(m00) + len(nist)))
        for vector in m00 + nist:
            aad, ciphertext = (bytes.fromhex(vector[field]) for field in ("aad", "ciphertext"))
            trace = ghash_trace(bytes.fromhex(vector["key"]), bytes.fromhex(vector["nonce"]),
                                aad, ciphertext)
            self.assertEqual(trace["tag"], vector["tag"], vector.get("name"))
            if "ghash" in vector:
                self.assertEqual(trace, vector["ghash"], vector.get("name"))
            chunks = [(0, aad[i:i + 16]) for i in range(0, len(aad), 16)]
            chunks += [(1, ciphertext[i:i + 16]) for i in range(0, len(ciphertext), 16)]
            self.assertEqual(len(chunks) + 1, len(trace["states"]))
            lines.append(f"{trace['h']} {len(chunks)}")
            for (kind, data), expected in zip(chunks, trace["states"]):
                lines.append(f"{kind} {len(data)} {data.ljust(16, bytes(1)).hex()} {expected}")
            lines.append(trace["states"][-1])  # Final length block is generated by RTL.

        with tempfile.TemporaryDirectory() as directory:
            work = Path(directory)
            vectors = work / "ghash_vectors.txt"
            vectors.write_text("\n".join(lines) + "\n")
            executable = work / "ghash.vvp"
            compile_iverilog([tool("iverilog"), "-g2012", "-s", "tb_ghash", "-o", str(executable),
                            str(ROOT / "board/src/rtl/crypto/gf128_mul.sv"),
                            str(ROOT / "board/src/rtl/crypto/ghash.sv"),
                            str(ROOT / "sim/tb/tb_ghash.sv")], executable)
            result = subprocess.run([tool("vvp"), str(executable), f"+VECTORS={vectors}"],
                                    capture_output=True, text=True, timeout=90, cwd=ROOT)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn("GHASH_PASS gf=32 cases=100 per_block=1 reset=1", result.stdout)
            print(result.stdout.strip())


if __name__ == "__main__":
    unittest.main(verbosity=2)
